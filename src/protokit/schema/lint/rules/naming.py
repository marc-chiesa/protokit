"""``naming`` rule pack — naming-case rules for protokit-lint.

D2 shipped the AIP-122 field-naming canary (``naming/snake-case-fields``).
D6a (Unit 3) extends the pack with the remaining naming-case rules
needed for buf BASIC parity: PascalCase for messages/enums/services/RPCs;
UPPER_SNAKE_CASE for enum values; lower_snake for oneofs/files/packages.

References:
- AIP-122 § "Field names":
  https://google.aip.dev/122
- buf BASIC rule catalog (parity targets named per-rule via
  ``source_spec="buf:<RULE_ID>"``).
- protokit-lint D2 plan:
  ``docs/plans/2026-05-02-001-feat-protokit-lint-d2-engine-plan.md``
- protokit-lint D6a plan:
  ``docs/plans/2026-05-12-001-feat-protokit-lint-d6a-rule-library-plan.md``

Module shape adopts the ``RULES`` attribute name from compat
(``schema/checker.py:217-220``) but its wire format differs: this
pack's ``RULES`` is a tuple of bare ``@lint_rule``-decorated
functions (the rule_id lives on ``fn._lint_spec``), whereas compat's
``RULES`` is ``(rule_id, plugin_fn)`` tuples. Lint packs cannot be
loaded into ``SchemaChecker`` and vice versa; the divergence is
documented in ``LintEngine.load_rule_pack``'s docstring.
"""

from __future__ import annotations

import re
from collections.abc import Callable
from pathlib import PurePosixPath
from typing import TYPE_CHECKING

from protokit.schema.lint.decorator import lint_rule
from protokit.schema.lint.model import ElementKind, LintSeverity

if TYPE_CHECKING:
    from protokit.schema.lint.model import (
        EnumLintContext,
        EnumValueLintContext,
        FieldLintContext,
        FileLintContext,
        MessageLintContext,
        MethodLintContext,
        OneofLintContext,
        ServiceLintContext,
    )


# AIP-122 snake_case: lowercase start, alphanumeric segments separated
# by single underscores. Rejects: BadCamelCase (uppercase),
# with__double (consecutive underscores), trailing_ (trailing
# underscore), with-dash (non-word character), UPPER (uppercase).
# Note: protobuf grammar already rejects leading-underscore field
# names at the source level; the regex would also reject them, but
# in practice that branch is dead.
_SNAKE_CASE_RE = re.compile(r"^[a-z][a-z0-9]*(_[a-z0-9]+)*$")

# PascalCase: an uppercase letter followed by zero or more alphanumeric
# characters. Matches buf's MESSAGE_PASCAL_CASE / ENUM_PASCAL_CASE /
# SERVICE_PASCAL_CASE / RPC_PASCAL_CASE which accept single-letter names
# (``A``), all-uppercase acronyms (``URL``), and mixed (``UserService``).
# Rejects: lowercase-leading (``userService``), embedded underscores
# (``User_v2``), leading underscore (``_Foo``).
_PASCAL_CASE_RE = re.compile(r"^[A-Z][A-Za-z0-9]*$")

# UPPER_SNAKE_CASE: uppercase-leading segment, alphanumeric uppercase
# segments separated by single underscores. Matches ``STATUS``,
# ``STATUS_ACTIVE``, ``STATUS_V2``. Rejects mixed-case
# (``StatusActive``, ``STATUS_active``), trailing underscore.
_UPPER_SNAKE_CASE_RE = re.compile(r"^[A-Z][A-Z0-9]*(_[A-Z0-9]+)*$")


@lint_rule(
    rule_id="naming/snake-case-fields",
    severity=LintSeverity.WARNING,
    profiles=("recommended", "default"),
    element=ElementKind.FIELD,
    message_template="Field {name!r} is not snake_case (AIP-122)",
    source_spec="https://google.aip.dev/122",
)
def check_snake_case_fields(ctx: FieldLintContext) -> None:
    """Fire on field names that don't match AIP-122 snake_case.

    Skips the synthetic ``key`` / ``value`` fields generated inside
    protobuf map-entry messages: their names are pre-defined by the
    protobuf compiler from ``map<K, V>`` declarations and are not
    user-authored, so a snake_case warning would be noise. The
    detection is on the field's containing type (the entry message
    has ``map_entry = true`` set in its options); the user-facing
    map field itself (e.g., ``attributes`` in
    ``map<string, string> attributes = 1;``) IS user-authored and
    IS linted normally.

    Profile membership widened in D6a Unit 3 from ``("default",)`` to
    ``("recommended", "default")`` — the canary joins the buf-parity
    rule set rather than living as a "default only" warning.
    """
    if ctx.field.containing_type.GetOptions().map_entry:
        return
    if not _SNAKE_CASE_RE.match(ctx.field.name):
        ctx.emit(
            violation_kind="naming/snake-case-fields",
            params={"name": ctx.field.name},
        )


@lint_rule(
    rule_id="naming/pascal-case-messages",
    severity=LintSeverity.ERROR,
    profiles=("recommended", "default"),
    element=ElementKind.MESSAGE,
    message_template="Message {name!r} is not PascalCase",
    source_spec="buf:MESSAGE_PASCAL_CASE",
)
def check_pascal_case_messages(ctx: MessageLintContext) -> None:
    """Fire on message names that don't match PascalCase.

    Skips synthetic map-entry messages (``<FieldName>Entry`` types
    auto-generated by the protobuf compiler from ``map<K, V>``
    declarations). These names ARE PascalCase by convention, but
    skipping the descriptor-pool-synthesized type entirely avoids
    coupling the rule's correctness to compiler naming choices and
    mirrors the canary's map-entry skip discipline.
    """
    if ctx.message.GetOptions().map_entry:
        return
    if not _PASCAL_CASE_RE.match(ctx.message.name):
        ctx.emit(
            violation_kind="naming/pascal-case-messages",
            params={"name": ctx.message.name},
        )


