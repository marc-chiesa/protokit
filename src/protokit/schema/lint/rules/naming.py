@lint_rule(
    rule_id="naming/snake-case-files",
    severity=LintSeverity.ERROR,
    profiles=("recommended", "default"),
    element=ElementKind.FILE,
    message_template="File basename {name!r} is not snake_case",
    source_spec="buf:FILE_LOWER_SNAKE_CASE",
)
def check_snake_case_files(ctx: FileLintContext) -> None:
    """Fire on .proto file basenames that don't match snake_case.

    Checks the file's basename only (the directory portion is
    ignored); ``acme/v1/Foo_Bar.proto`` fires on the stem
    ``Foo_Bar``, ``acme/v1/foo_bar.proto`` is clean. Uses
    ``PurePosixPath`` so the rule produces identical results
    regardless of the host platform — proto file names recorded in
    the descriptor pool use POSIX separators by protobuf convention.

    Multi-dot filenames (e.g., ``acme.v1.proto``) resolve to a stem
    containing the inner dot (``acme.v1``) because ``PurePosixPath``
    strips only the final extension. The dot is not in the
    ``_SNAKE_CASE_RE`` character class, so such filenames fire. This
    matches buf's FILE_LOWER_SNAKE_CASE behavior: a ``.proto`` file
    is expected to have a single dot before its extension. Users
    encoding version segments in the filename should put them in
    the directory path (e.g., ``acme/v1/users.proto``) rather than
    the basename.
    """
    stem = PurePosixPath(ctx.file.name).stem
    if not _SNAKE_CASE_RE.match(stem):
        ctx.emit(
            violation_kind="naming/snake-case-files",
            params={"name": stem},
        )


@lint_rule(
    rule_id="naming/snake-case-packages",
    severity=LintSeverity.ERROR,
    profiles=("recommended", "default"),
    element=ElementKind.FILE,
    message_template=(
        "Package {package!r} has segment {segment!r} that is not snake_case"
    ),
    source_spec="buf:PACKAGE_LOWER_SNAKE_CASE",
)
def check_snake_case_packages(ctx: FileLintContext) -> None:
    """Fire on package segments that don't match snake_case.

    Splits ``ctx.file.package`` on ``.`` and checks each segment.
    A missing-package file (empty ``package``) is the concern of
    the separate ``package/defined`` rule (D6a Unit 6) and is
    skipped here — this rule speaks only to the case-shape of
    declared segments. Multi-segment packages fire one finding per
    offending segment so the report enumerates every violation
    rather than collapsing them into a single ambiguous message.
    """
    if not ctx.file.package:
        return
    for segment in ctx.file.package.split("."):
        if not _SNAKE_CASE_RE.match(segment):
            ctx.emit(
                violation_kind="naming/snake-case-packages",
                params={"package": ctx.file.package, "segment": segment},
            )


# Module-level RULES tuple — same attribute name as compat
# (``schema/checker.py:217-220``) but holding bare decorated callables,
# not (rule_id, fn) tuples. ``LintEngine.load_rule_pack`` reads this
# attribute and extracts each fn's ``_lint_spec``.
RULES: tuple[Callable[..., None], ...] = (
    check_snake_case_fields,
    check_pascal_case_messages,
    check_pascal_case_enums,
    check_upper_snake_case_enum_values,
    check_snake_case_oneofs,
    check_pascal_case_services,
    check_pascal_case_rpcs,
    check_snake_case_files,
    check_snake_case_packages,
)
