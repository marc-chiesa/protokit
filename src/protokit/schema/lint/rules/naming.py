@lint_rule(
    rule_id="naming/snake-case-oneofs",
    severity=LintSeverity.ERROR,
    profiles=("recommended", "default"),
    element=ElementKind.ONEOF,
    message_template="Oneof {name!r} is not snake_case",
    source_spec="buf:ONEOF_LOWER_SNAKE_CASE",
)
def check_snake_case_oneofs(ctx: OneofLintContext) -> None:
    """Fire on oneof names that don't match snake_case.

    Skips proto3 synthetic oneofs generated by ``optional`` fields.
    The protobuf compiler synthesizes a wrapper oneof for each
    ``optional <type> <name>`` declaration and names it
    ``_<field-name>``. The leading underscore is a reliable
    discriminator because protobuf grammar prohibits user-authored
    oneof names from starting with an underscore: any oneof whose
    name begins with ``_`` is therefore compiler-synthesized rather
    than user-declared, and a snake_case finding on the synthetic
    name would be a false positive on a common proto3 idiom. This
    matches buf's ONEOF_LOWER_SNAKE_CASE which similarly excludes
    synthetic oneofs from its check.
    """
    if ctx.oneof.name.startswith("_"):
        return
    if not _SNAKE_CASE_RE.match(ctx.oneof.name):
        ctx.emit(
            violation_kind="naming/snake-case-oneofs",
            params={"name": ctx.oneof.name},
        )


